export const STRINGS = { fr, en, es };
export const LANGS = [
  { code: 'fr', label: 'FR' },
  { code: 'en', label: 'EN' },
  { code: 'es', label: 'ES' },
];

export function detectLang() {
  try {
    const code = (getLocales()[0]?.languageCode || 'en').toLowerCase();
    return STRINGS[code] ? code : 'en';
  } catch {
    return 'en';
  }
}

export function countryName(country, lang) {
  if (!country) return '';
  return country[`name_${lang}`] || country.name_en;
}
